"""
Writes android/.../NeoGeoNames.kt (Neo Geo romset short name -> long name) from pwa/public/db/neogeo.json.
Run from the repo root after `npm run build-db -- neogeo`:  python pwa/scripts/neogeo-names-kt.py
"""
import json

SRC = 'pwa/public/db/neogeo.json'
OUT = 'android/app/src/main/java/com/retrostick/launcher/NeoGeoNames.kt'


def kt(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


d = json.load(open(SRC, encoding='utf-8'))
rows = sorted(d['files'].items())
lines = [
    'package com.retrostick.launcher',
    '',
    '/**',
    ' * Neo Geo romsets: short name (the file, "mslug.zip", which FinalBurn Neo needs as is) -> the game\'s long name, from',
    ' * pwa/public/db/neogeo.json (libretro\'s Neo Geo list plus FinalBurn Neo\'s own). Generated by',
    ' * pwa/scripts/neogeo-names-kt.py after `npm run build-db -- neogeo`. The title shown is [romsetTitle] of the long name.',
    ' */',
    'object NeoGeoNames {',
    '    fun long(short: String): String? = NAMES[short.lowercase()]',
    '',
    '    /** "Samurai Shodown / Samurai Spirits (NGM-045)" -> "Samurai Shodown": the first (English) name, no board codes. */',
    '    fun romsetTitle(long: String): String = long.split(Regex(" [/_] "))[0].replace(Regex("""\\s*[(\\[].*$"""), "").trim()',
    '',
    '    private val NAMES: Map<String, String> = hashMapOf(',
]
lines += [f'        {kt(k)} to {kt(d["names"][i])},' for k, i in rows]
lines += ['    )', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(rows), 'romsets ->', OUT)
