"""Convert the mockup console logos (simple Illustrator SVGs) into Android VectorDrawables.

Supports what those files use: <g transform="translate(..)">, <path>, <polygon>, <rect>,
flat fills and linearGradient fills (flattened to their first stop colour).
Elements with opacity 0 are skipped.

Usage: python tools/svg2vd.py <in.svg> <out.xml> [height_dp]
"""
import re
import sys
import xml.etree.ElementTree as ET


def local(tag):
    return tag.rsplit('}', 1)[-1]


def style_value(el, name):
    m = re.search(name + r'\s*:\s*([^;]+)', el.get('style', ''))
    return m.group(1).strip() if m else None


def colour(value):
    value = value.strip()
    if re.fullmatch(r'#[0-9a-fA-F]{3}', value):
        value = '#' + ''.join(c * 2 for c in value[1:])
    return value.upper()


def main(src, dst, height_dp=48.0):
    root = ET.parse(src).getroot()
    min_x, min_y, vw, vh = (float(v) for v in re.split(r'[\s,]+', root.get('viewBox').strip()))

    gradients = {}
    for el in root.iter():
        if local(el.tag) in ('linearGradient', 'radialGradient'):
            stop = next((s for s in el if local(s.tag) == 'stop'), None)
            if stop is not None:
                gradients[el.get('id')] = colour(style_value(stop, 'stop-color') or stop.get('stop-color'))

    out = []

    def fill_of(el):
        fill = el.get('fill') or style_value(el, 'fill') or '#000000'
        m = re.fullmatch(r'url\(#(.+)\)', fill)
        if m:
            return gradients.get(m.group(1), '#000000')
        return None if fill == 'none' else colour(fill)

    def emit(el, depth):
        tag = local(el.tag)
        pad = '    ' * depth
        if el.get('opacity') in ('0', '0.0') or tag in ('defs', 'linearGradient', 'radialGradient', 'metadata'):
            return
        if tag in ('g', 'svg'):
            m = re.search(r'translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)', el.get('transform', ''))
            if tag == 'g' and m:
                out.append(f'{pad}<group android:translateX="{m.group(1)}" android:translateY="{m.group(2)}">')
                for child in el:
                    emit(child, depth + 1)
                out.append(f'{pad}</group>')
            else:
                for child in el:
                    emit(child, depth)
            return
        if tag == 'path':
            d = ' '.join(el.get('d').split())
        elif tag in ('polygon', 'polyline'):
            pts = re.split(r'[\s,]+', el.get('points').strip())
            pairs = [f'{pts[i]},{pts[i + 1]}' for i in range(0, len(pts) - 1, 2)]
            d = 'M' + ' L'.join(pairs) + (' Z' if tag == 'polygon' else '')
        elif tag == 'rect':
            x, y = float(el.get('x', 0)), float(el.get('y', 0))
            w, h = float(el.get('width')), float(el.get('height'))
            d = f'M{x},{y} h{w} v{h} h{-w} Z'
        else:
            return
        fill = fill_of(el)
        if fill:
            out.append(f'{pad}<path android:fillColor="{fill}" android:pathData="{d}"/>')

    emit(root, 2)
    width_dp = round(height_dp * vw / vh, 1)
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write(f'<!-- Generated by tools/svg2vd.py from {src.replace(chr(92), "/").split("/")[-1]} -->\n')
        f.write('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n')
        f.write(f'    android:width="{width_dp}dp" android:height="{height_dp}dp"\n')
        f.write(f'    android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n')
        f.write(f'    <group android:translateX="{-min_x}" android:translateY="{-min_y}">\n')
        f.write('\n'.join(out) + '\n')
        f.write('    </group>\n</vector>\n')
    print(f'{dst}: {len(out)} elements, {width_dp}x{height_dp}dp')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], float(sys.argv[3]) if len(sys.argv) > 3 else 48.0)
